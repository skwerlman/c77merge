#![feature(fn_traits)]

use std::error::Error;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;
use std::process::exit;
use std::sync::Arc;
use std::time::Duration;

use clap::Parser;
use futures::FutureExt as _;
use futures::future::join_all;
use itertools::{Either, Itertools};
use miette::{IntoDiagnostic, Result, miette};
use tokio::time::sleep;
use tracing::{debug, error, info, instrument, trace, trace_span, warn};
use tracing_subscriber::fmt::format::FmtSpan;
use tracing_subscriber::{EnvFilter, fmt, prelude::*};

use c77conf::mod_profile::{ModInfo, ModProfile, Profile};
use c77conf::{Configuration, get_games, get_main_config};
use c77merge::hash_mod::hash_all_in_dir;
use nexusapi::login;
use nexusapi::md5lookup::Md5LookupResult;

#[derive(Parser, Debug)]
struct Cli {
    game: String,
    profile: String,
}

#[tokio::main]
async fn main() -> Result<()> {
    human_panic::setup_panic!();
    let format = fmt::format::format().pretty();
    let filter = EnvFilter::try_from_env("C77_LOG").unwrap_or_else(|_| EnvFilter::new("debug"));
    fmt()
        .event_format(format)
        .with_env_filter(filter)
        .with_span_events(FmtSpan::NEW | FmtSpan::CLOSE)
        .finish()
        .init();

    let _mainspan = trace_span!("main").entered();

    let cli_span = trace_span!("cli").entered();
    let cli = Cli::parse();
    trace!("cli: {cli:?}");
    cli_span.exit();

    let config_span = trace_span!("configs").entered();
    let settings: Arc<Configuration> = Arc::new(get_main_config()?);
    trace!("config: {:?}", settings.mask_api_key());

    let games = get_games(&settings)?;
    trace!("games: {games:?}");

    let game = games
        .iter()
        .find(|g| g.aliases.contains(&cli.game))
        .ok_or_else(|| miette!("Game not found"))?;

    config_span.exit();

    info!("Looking at mods for {}", game.name);

    let login_span = trace_span!("login").entered();
    // start login process before hashing mods
    let api_future = tokio::task::spawn(login(settings));
    let login_span = login_span.exit();

    let hash_span = trace_span!("hash").entered();

    let (mod_hashes, errors) = hash_all_in_dir(game.download_dir().as_path())?;

    if errors.has_errors() {
        error!("{errors}");
    }

    let h = hash_span.exit();
    drop(h);

    let login_span = login_span.entered();
    // await login process since we need the api client to get mod info
    let (api_client, _userinfo, limiter) = match api_future.await.into_diagnostic()? {
        Ok((partial_api_client, userinfo, limiter)) => {
            let full_api_client = partial_api_client.with_domain(&game.domain);
            (full_api_client, userinfo, limiter)
        }
        Err(err) => {
            error_report(&err);
            sleep(Duration::from_millis(75)).await;
            exit(1)
        }
    };
    login_span.exit();

    let api_client_clone = api_client.clone();

    // schedule periodic rate limiter refreshes
    tokio::spawn(async move {
        loop {
            let resp = nexusapi::refresh_limits(api_client_clone.clone(), &limiter).await;
            if let Err(err) = resp {
                error_report(&err);
            }
            tokio::time::sleep(Duration::from_secs(180)).await;
        }
    });

    let mod_info_span = trace_span!("mod info").entered();

    let mut mod_futures = Vec::new();

    for hash in mod_hashes {
        mod_futures.push(tokio::task::spawn(nexusapi::get_by_hash(
            api_client.clone(),
            hash,
        )));
    }

    let (mut mods, errors): (Vec<ModInfo>, Vec<nexusapi::error::Error>) = join_all(mod_futures)
        .then(async |r| -> Vec<Result<ModInfo, nexusapi::error::Error>> {
            r.into_iter()
                .flatten()
                .map(|mm| mm.map(|m| mod_entry_from_md5_lookup(&game.path, m)))
                .collect()
        })
        .await
        .into_iter()
        .partition_map(|r| match r {
            Ok(v) => Either::Left(v),
            Err(e) => Either::Right(e),
        });

    for err in errors {
        error_report(&err);
    }
    mod_info_span.exit();

    let profile_span = trace_span!("profile").entered();
    let profile_contruction_span = trace_span!("profile build").entered();

    profile_contruction_span.exit();

    let sort_span = trace_span!("mod sort").entered();
    mods.sort_unstable_by_key(|m| (m.id, m.fid));
    sort_span.exit();

    let profile = Profile {
        name: cli.profile,
        description: "Autogenerated mod profile".to_string(),
    };

    let mod_profile = ModProfile { profile, mods };

    let write_span = trace_span!("write profile").entered();
    let profile_file = game.profile(&mod_profile.profile.name);

    info!("Writing profile...");

    fs::write(profile_file, mod_profile.as_toml()?)
        .map_err(|e| miette!("Failed to write profile: {e}"))?;
    write_span.exit();

    profile_span.exit();
    info!("Done!");

    Ok(())
}

#[instrument(level = "trace")]
fn mod_entry_from_md5_lookup(game_base: &Path, lookup: Md5LookupResult) -> ModInfo {
    let id = lookup.mod_details.mod_id;
    let fid = lookup.file_details.file_id;
    let unpacked = Path::new(&lookup.file_details.file_name).with_extension("");
    let archive = Path::new(&lookup.file_details.file_name).into();

    let archive_path = game_base.join("Download").join(&archive);

    match archive_path.try_exists() {
        Ok(true) => { /* noop */ }
        Ok(false) => {
            warn!(
                "Could not find the archive for '{}'! Was it renamed?",
                lookup.mod_details.name
            );
            debug!("Looked at: {archive_path:?}");
        }
        Err(e) => {
            error!(
                "Could not find the archive for '{}': {e}",
                lookup.mod_details.name
            );
            debug!("Looked at: {archive_path:?}");
        }
    }

    let unpacked_path = game_base.join("Mods").join(Path::new(&unpacked));

    match unpacked_path.try_exists() {
        Ok(true) => { /* noop */ }
        Ok(false) => {
            warn!(
                "Could not find the unpacked mod directory for '{}'! Was it renamed?",
                lookup.mod_details.name
            );
            debug!("Looked at: {unpacked_path:?}");
        }
        Err(e) => {
            error!(
                "Could not find the unpacked mod directory for '{}': {e}",
                lookup.mod_details.name
            );
            debug!("Looked at: {unpacked_path:?}");
        }
    }

    ModInfo {
        id,
        fid,
        archive,
        unpacked,
    }
}

fn error_report(err: &dyn Error) {
    let mut s = format!("{err}\n{err:?}");
    let mut err: &(dyn Error) = err;
    while let Some(src) = err.source() {
        let _ = write!(s, "\n\nCaused by: {src}\n{src:?}");
        err = src;
    }
    error!("{s}");
}
